def render_score():
    # Existing strictly label-free raster generator, real compressed FITS,
    # TAN WCS, real render chain, and all 96 Fourier estimators. No labels.
    obj = medium_tests.raster(900000, 'flip')
    wcs = medium._source_wcs(obj)
    arrays = []
    for key in ('image', 'maskbits', 'nexp'):
        stream = io.BytesIO()
        fits.HDUList([fits.PrimaryHDU(), fits.CompImageHDU(obj[key],
            header=wcs.to_header(), compression_type='RICE_1')]).writeto(stream)
        raw = stream.getvalue()
        rp.write_new(WORK / ('synthetic.' + key + '.fits'), raw)
        with fits.open(io.BytesIO(raw), memmap=False) as hdus:
            arrays.append(np.array(hdus[1].data, copy=True))
            if key == 'image':
                loaded_wcs = WCS(hdus[1].header, relax=False)
    receipt = medium._chain.render_object(*arrays, loaded_wcs, obj['ra'], obj['dec'],
        obj['brick'], medium._chain.pr.r_t_validation())
    rp.require(receipt['status'] == 'SCORED', 'SYNTHETIC-RENDER-FAILED')
    tensor = receipt.pop('tensor')
    rp.require(rp.sha(tensor) == receipt['tensor_sha256'], 'TENSOR-INTEGRITY')
    rp.write_new(WORK / 'synthetic.f32', tensor)
    arr = np.frombuffer(tensor, dtype='<f4').reshape(128, 128)
    scores = []
    for index, cfg in enumerate(fc.enumerate_configs()):
        estimator = fc.Estimator(cfg)
        first, second = estimator.chi(arr), estimator.chi(arr.copy())
        rp.require(first.view(np.uint32) == second.view(np.uint32), 'NON-REPEAT')
        rp.require(np.isfinite(first) and first != 0, 'TIE-OR-NONFINITE')
        scores.append({'config_index': index, 'chi_bits': int(first.view(np.uint32)),
                       'repeat_bits': int(second.view(np.uint32))})
    rp.require(len(scores) == 96, 'CONFIG-COUNT')
    save(WORK / 'label_blind_scores.json', {'render': receipt, 'scores': scores})
    tests = suite_run('medium', unittest.defaultTestLoader.loadTestsFromTestCase(
        medium_tests.MediumPerturbationTests))
    return {'compressed_fits_planes': 3, 'render': receipt['status'],
            'real_estimators': 96, 'bitwise_repeat': True, 'labels_read': 0, **tests}

