sys.path.insert(0, str(Path(__file__).resolve().parent))
import successor_ref_v9 as V9          # noqa: E402  the frozen constants and the production branch

A_LONGO = V9.A_LONGO
P_REPRODUCED = V9.P_REPRODUCED
P_REJECT_MIN = V9.P_REJECT_MIN

CODES = {
    "T01": "p_of_A is not non-increasing in |A| over the scanned range",
    "T02": "a supplied scale is not finite or not positive",
}
# T03 used to be declared here - "the transcribed verdict disagrees with the production predicate" -
# and was never emitted by any runtime path. The transcription agreement IS checked, but by
# self_test() against v9._decide_from(), which is a build-time assertion and not a per-call refusal.
# A CODES dict that advertises a refusal the module cannot produce overstates its refusal surface,
# so T03 is removed rather than faked. self_test() now asserts the dict has no orphans.


def verdict_at(A: float, p: float, sigma_comb: float, sig_band: float, floor: float) -> str:
    """Transcription of `successor_ref_v9.py:1579-1584`. Kept in this shape deliberately so the
    correspondence is checkable line by line, and asserted on a grid by `self_test()`."""
    if p < P_REPRODUCED and A > 0.0 and abs(A - A_LONGO) <= 3.0 * sigma_comb and A >= floor:
        return "REPRODUCED-LONGO"
    elif p > P_REJECT_MIN and (abs(A) + 3.0 * sig_band) < A_LONGO:
        return "REJECTED-AT-LONGO-AMPLITUDE"
    return "INCONCLUSIVE"


def _p_gate_crossings(p_of_A, lo: float, hi: float, n: int = 20001):
    """The |A| values where p(A) crosses each gate, by bisection on a monotone function.

    Returns both signs, because the branch conditions test `A > 0` and `abs(A)`.
    """
    out = []
    for gate in (P_REPRODUCED, P_REJECT_MIN):
        a, b = 0.0, max(abs(lo), abs(hi))
        if b <= 0.0:
            continue
        # p is non-increasing in |A|; find |A| with p(|A|) == gate if it is bracketed.
        if not (p_of_A(a) >= gate >= p_of_A(b)):
            continue
        for _ in range(200):
            m = 0.5 * (a + b)
            if p_of_A(m) > gate:
                a = m
            else:
                b = m
        x = 0.5 * (a + b)
        out.extend([x, -x])
    return out


def breakpoints(p_of_A, sigma_comb: float, sig_band: float, floor: float,
                lo: float, hi: float) -> tuple[list[float], list[str]]:
    """Return (sorted complete breakpoint set within [lo, hi], refusals).

    Every branch condition in `verdict_at` contributes its equality locus:

        A > 0.0                              ->  A = 0
        |A - A_LONGO| <= 3*sigma_comb        ->  A = A_LONGO -+ 3*sigma_comb
        A >= floor                           ->  A = floor
        (|A| + 3*sig_band) < A_LONGO         ->  A = -+(A_LONGO - 3*sig_band)
        p < P_REPRODUCED, p > P_REJECT_MIN   ->  the |A| where p crosses each gate
    """
    bad: list[str] = []
    for name, v in (("sigma_comb", sigma_comb), ("sig_band", sig_band)):
        if not (v == v and v > 0.0 and v != float("inf")):
            bad.append(f"[T02] {name} = {v!r} is not finite and positive")
    if not (floor == floor and floor != float("inf")):
        bad.append(f"[T02] floor = {floor!r} is not finite")
    if bad:
        return [], bad

    # Monotonicity is an assumption; enforce it rather than trust it.
    grid = [lo + (hi - lo) * i / 400.0 for i in range(401)]
    ps = [p_of_A(abs(x)) for x in grid]
    xs = sorted(zip((abs(x) for x in grid), ps))
    for (x0, p0), (x1, p1) in zip(xs, xs[1:]):
        if p1 > p0 + 1e-12:
            bad.append(f"[T01] p rose from {p0:.6g} at |A|={x0:.6g} to {p1:.6g} at |A|={x1:.6g}")
            break
    if bad:
        return [], bad

    edge = A_LONGO - 3.0 * sig_band
    cand = [0.0,
            A_LONGO - 3.0 * sigma_comb, A_LONGO + 3.0 * sigma_comb,
            floor,
            edge, -edge]
    cand.extend(_p_gate_crossings(p_of_A, lo, hi))
    return sorted({round(c, 15) for c in cand if lo <= c <= hi}), []


def invariant_over(A_hat: float, gamma: float, p_of_A, sigma_comb: float, sig_band: float,
                   floor: float) -> tuple[bool, dict]:
    """Is the verdict identical across the whole systematic interval?

    Exact, not sampled: the verdict is piecewise constant in `A`, so it suffices to evaluate at both
    endpoints and immediately either side of every breakpoint inside the interval.
    """
    lo, hi = A_hat - abs(gamma), A_hat + abs(gamma)
    T, bad = breakpoints(p_of_A, sigma_comb, sig_band, floor, lo, hi)
    if bad:
        return False, {"refusals": bad, "T": [], "verdicts": []}
    eps = 1e-12
    probes = [lo, hi]
    for t in T:
        probes.extend([t - eps, t, t + eps])
    probes = [x for x in probes if lo - eps <= x <= hi + eps]
    seen = {verdict_at(x, p_of_A(abs(x)), sigma_comb, sig_band, floor) for x in probes}
    return len(seen) == 1, {"refusals": [], "T": T, "verdicts": sorted(seen),
                            "interval": [lo, hi], "n_probes": len(probes)}


# ── Controls: GPT56's list, plus the transcription check that is the real trust root. ────────────

def _p_step(scale=0.02):
    """A monotone non-increasing p(|A|): 1 at 0, falling through both gates."""
    import math
    return lambda a: math.exp(-abs(a) / scale)


def self_test() -> int:
    print("verdict-breakpoint self-test")
    fails = []
    p_of_A = _p_step()
    sc, sb, fl = 0.004, 0.003, 0.010

    # 1. TRANSCRIPTION, against PRODUCTION ITSELF. GPT56 found the previous version compared
    #    verdict_at() to another local restatement of the same if/elif - a control that could not
    #    fail, in the check called the trust root. This calls v9's own `_decide_from()` and takes
    #    its sigma/floor back out of the returned record, so the comparison is against the
    #    production decision rather than against a copy of my own transcription.
    import itertools
    import numpy as _np

    class _Mask:                      # _decide_from only reads .n and .digest for the record
        n, digest = 49211, "fixture"

    # a_lb_b must clear v9's A_FLOOR = 0.85 or adjudicate_path raises InconclusiveByCalibration -
    # the prereg's own pre-unblinding calibration halt, enforced in the production code.
    cal = {"a_hat": 0.90, "sigma_a": 0.01, "a_lb": 0.87,
           "a_b": _np.array([0.90, 0.90, 0.90]), "a_lb_b": _np.array([0.87, 0.87, 0.87]),
           "cov_a": _np.eye(3) * 1e-4}
    assert V9.adjudicate_path(cal) == "SCALAR", "fixture must select the scalar path"
    w = 2.0 * cal["a_hat"] - 1.0
    n_checked = 0
    for A_target, p in itertools.product(
            [-0.08, -0.0408, -0.001, 0.0, 0.001, 0.02, 0.0408, 0.08],
            [0.0005, 0.001, 0.01, 0.05, 0.06, 0.9]):
        rec = V9._decide_from(A_target * w, p, 0.002, _Mask(), cal)
        mine = verdict_at(rec["A_L"], p, rec["sigma_comb"], rec["sigma_ours_band"],
                          rec["evaluated_floor"])
        n_checked += 1
        if mine != rec["verdict"]:
            fails.append(f"transcription A={A_target} p={p}: {mine} != {rec['verdict']}")
    print(f"  {'OK  ' if not fails else 'FAIL'} transcription matches v9._decide_from() "
          f"on {n_checked} (A, p) points")

    # 2. Every branch condition contributes its locus, and the p gates appear as A-values.
    T, bad = breakpoints(p_of_A, sc, sb, fl, -0.2, 0.2)
    expect_near = [0.0, A_LONGO - 3 * sc, A_LONGO + 3 * sc, fl,
                   A_LONGO - 3 * sb, -(A_LONGO - 3 * sb)]
    missing = [e for e in expect_near if not any(abs(e - t) < 1e-9 for t in T)]
    p_gates = [t for t in T if t not in expect_near and abs(t) > 1e-9]
    ok = not bad and not missing and len(p_gates) >= 2
    print(f"  {'OK  ' if ok else 'FAIL'} T has {len(T)} breakpoints incl. {len(p_gates)} from the "
          f"p gates{'' if ok else f' — missing {missing}, bad {bad}'}")
    if not ok:
        fails.append("breakpoint completeness")

    # 3. Invariance behaviour: wide interval spanning a boundary must NOT be invariant; a narrow
    #    interval inside one region must be.
    # NOTE on the third case: crossing A = 0 does NOT by itself flip the verdict when the p gate
    # for REPRODUCED is unsatisfied — the branch needs p < 0.001 as well. An earlier version of this
    # test asserted otherwise and the code was right; a breakpoint is a place the verdict MAY change,
    # not one where it must. The steep-p case below is one where it actually does.
    steep = _p_step(0.005)          # p(A_LONGO) ~ 2.9e-4, so REPRODUCED is reachable
    for name, A_hat, g, want, pf in (
            ("narrow, interior", 0.0800, 0.0005, True, p_of_A),
            ("spans the band edge", A_LONGO, 0.02, False, p_of_A),
            ("flat p, crossing A=0 changes nothing", 0.0, 0.01, True, p_of_A),
            ("steep p, spans REPRODUCED edge", A_LONGO, 0.02, False, steep),
            ("steep p, interior of REPRODUCED", A_LONGO, 0.0005, True, steep)):
        inv, info = invariant_over(A_hat, g, pf, sc, sb, fl)
        ok = inv == want
        print(f"  {'OK  ' if ok else 'FAIL'} {name}: invariant={inv} (want {want}), "
              f"verdicts={info['verdicts']}")
        if not ok:
            fails.append(name)

    # 4. Refusals fire.
    for name, args, code in (
            ("non-monotone p", (lambda a: min(1.0, 0.1 + a), sc, sb, fl, -0.2, 0.2), "T01"),
            ("non-finite scale", (p_of_A, float("nan"), sb, fl, -0.2, 0.2), "T02")):
        T2, bad2 = breakpoints(*args)
        got = {r[1:4] for r in bad2}
        ok = got == {code} and T2 == []
        print(f"  {'OK  ' if ok else 'FAIL'} {name}: {sorted(got) or 'ACCEPTED'}")
        if not ok:
            fails.append(name)

    # Every declared code must be emittable by some runtime path. A declared-but-unemitted code
    # advertises a refusal the module cannot produce - the same overclaim shape as a control name
    # that asserts more than its predicate tests. T03 was exactly that and is gone.
    import re as _re
    src = Path(__file__).read_text()
    emitted = set(_re.findall(r"\[\{?(T\d{2})", src))
    orphans = sorted(set(CODES) - emitted)
    ok = not orphans
    print(f"  {'OK  ' if ok else 'FAIL'} every declared code is emitted by a runtime path"
          f"{'' if ok else f' — orphans {orphans}'}")
    if not ok:
        fails.append("orphan codes")

    print(f"  self-test: {len(fails)} failure(s)")
    return 1 if fails else 0


def main() -> int:
    import argparse
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args()
    if a.self_test:
        return self_test()
    T, bad = breakpoints(_p_step(), 0.004, 0.003, 0.010, -0.2, 0.2)
    print("complete breakpoint set T on the reference scales:")
    for t in T:
        print(f"  {t:+.9f}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
