"""The complete breakpoint set `T` of the production verdict, derived rather than listed.

WHY THIS EXISTS
---------------
The sensitivity-gradient rule says: the verdict is invariant on `[A-Gamma, A+Gamma]` iff no
breakpoint lies inside it. Both referee seats found that rule exact **only if `T` is complete**, and
that the design had deferred completeness to "a future receipt". GPT56: *"A future receipt can
authenticate a supplied set; it cannot establish that no omitted production branch changes verdict
inside the interval."* That is answer-determining freedom left open after the freeze, which is
precisely what a preregistration exists to close.

CODEX found the sharper half: the production verdict at `successor_ref_v9.py:1579-1584` also
branches on `p < P_REPRODUCED` and `p > P_REJECT_MIN`, and **`A` and `p` are both functions of the
same accepted-sign vector**, so varying `A` alone cannot establish invariance.

REFUTED 2026-08-29 BY BOTH SEATS — READ THIS BEFORE RELYING ON ANYTHING BELOW
----------------------------------------------------------------------------
**The central reduction below is FALSE and this module does not close T-completeness.**

CODEX: "the production p-value is not a function of |A|, and its null is not geometry-only... its
null depends on the observed sign multiset, which a gain gradient can change." GPT56 independently:
the reduction "is false for the actual permutation statistic", the module "takes an externally
supplied p_of_A rather than deriving one from production", and its monotonicity assumption is only
SAMPLED on a 401-point grid, so an interior p-gate crossing can be missed and a false invariance
returned.

I argued the permutation null is a property of the sample geometry that a gain gradient does not
move. That is wrong: the null is built from the observed signs, and a gain gradient changes them.

What survives: the amplitude-side breakpoint derivation (A=0, the band edges, the floor, the
rejection edge) and the transcription check against the production branch. What does NOT survive is
the claim that folding the p gates into A-breakpoints makes T complete. **Do not cite this module
as closing the p-gated freeze blocker.** See OPEN_QUESTION and the v5 reports.

THE ORIGINAL (REFUTED) ARGUMENT, KEPT FOR THE RECORD
---------------------------------------------------
`A` and `p` are not two independent freedoms. `p` is the permutation p-value of the same dipole
statistic that determines `A`, evaluated against a null generated by permuting positions. That null
is a property of the sample geometry and is **not moved by a gain gradient**, which rescales the
signal rather than the geometry. So `p` is a monotone non-increasing function of `|A|` through the
frozen null, and each `p`-gate maps to a definite `A` value:

    A_p_repro  = the |A| at which p(A) crosses P_REPRODUCED
    A_p_reject = the |A| at which p(A) crosses P_REJECT_MIN

**With those included, `T` is complete in `A` alone** and the interval test is exact again.

WHAT IS AND IS NOT CLAIMED
--------------------------
`breakpoints()` is derived from the branch conditions of `verdict_at()`, and `verdict_at()` is a
transcription of the production branch. **The transcription is the trust root**: `self_test()`
asserts it against the production predicate on a grid, so a divergence is caught rather than
assumed. This does not measure `gamma_hat`, does not bound routes (a) or (c), and does not close
conditional independence.

The monotonicity of `p` in `|A|` is an ASSUMPTION about the permutation null, stated here and
enforced: `p_of_A` must be non-increasing in `|A|`, and `breakpoints()` refuses if the supplied
callable is not.
"""
from __future__ import annotations

import sys
